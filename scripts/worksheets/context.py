"""Give the AI summary the words around each blank.

    python3 scripts/worksheets/context.py

Reads    worksheets/source/*.pdf
         shared/worksheet-fields.js       (written by build.py)
Writes   server/worksheet-context.js      (server only — never sent to the browser)

The fill-in fields only have positions, so on their own a saved answer is
just "p2-f3: Lisbon". This script looks up the printed text next to each
field in the PDF (the prompt it answers) and a short excerpt of each page,
so the AI summary can tell what a student was answering.

Run it after build.py whenever a worksheet is added or changed.
"""

import json
import re
import sys
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "worksheets" / "source"
FIELDS_JS = ROOT / "shared" / "worksheet-fields.js"
OUT = ROOT / "server" / "worksheet-context.js"

HEADER_PT = 175          # coloured title band at the top of each page
MAX_LABEL = 160          # characters per field label
MAX_PAGE_TEXT = 1200     # characters of page text per page


def load_fields():
    src = FIELDS_JS.read_text(encoding="utf-8")
    m = re.search(r"const worksheets = (\{.*\});", src, re.S)
    if not m:
        raise SystemExit("Could not read shared/worksheet-fields.js — run build.py first.")
    return json.loads(m.group(1))


def clean(text, limit):
    text = re.sub(r"\s+", " ", text).strip(" :-–—_.•")
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def line_words(words, y0, y1):
    """Words whose vertical middle falls inside [y0, y1]."""
    return [w for w in words if y0 <= (w[1] + w[3]) / 2 <= y1]


def join_words(ws):
    ws = sorted(ws, key=lambda w: (round(w[1] / 4), w[0]))
    return " ".join(w[4] for w in ws)


def label_for(field, words, pw, ph):
    x0, y0 = field["x"] * pw, field["y"] * ph
    x1, y1 = x0 + field["w"] * pw, y0 + field["h"] * ph
    pad = max(4.0, (y1 - y0) * 0.6) if field["type"] != "textarea" else 6.0
    band = line_words(words, y0 - pad, y1 + 2) if field["type"] != "textarea" else []

    if field["type"] == "checkbox":
        # the option text usually follows the tick box on the same line
        right = [w for w in band if w[0] >= x1 - 1 and w[0] - x1 < 260]
        if right:
            return clean(join_words(right), MAX_LABEL)
    if field["type"] != "textarea":
        # "Name: ______" — the prompt sits to the left on the same line
        left = [w for w in band if w[2] <= x0 + 2 and x0 - w[2] < 260]
        if left:
            return clean(join_words(left), MAX_LABEL)

    # words inside the box (a short label such as "1." or a printed prompt)
    inside = [w for w in words if w[0] >= x0 - 2 and w[2] <= x1 + 2 and w[1] >= y0 - 2 and w[3] <= y1 + 2]
    # otherwise the nearest line of text above it, overlapping horizontally
    above = [w for w in words if w[3] <= y0 + 2 and y0 - w[3] < 60 and w[2] > x0 - 20 and w[0] < x1 + 20]
    if above:
        nearest = max(w[3] for w in above)
        above = [w for w in above if nearest - w[3] < 14]
    text = join_words(above) + (" " + join_words(inside) if inside else "")
    return clean(text, MAX_LABEL) if text.strip() else ""


def main():
    catalog = load_fields()
    out = {}
    for doc_id, sheet in catalog.items():
        pdf = SRC / f"{doc_id}.pdf"
        if not pdf.exists():
            print(f"  missing {pdf.name}, skipped", file=sys.stderr)
            continue
        doc = pymupdf.open(pdf)
        title = ""
        pages = []
        labels = {}
        for pno, (page, info) in enumerate(zip(doc, sheet["pages"]), start=1):
            pw, ph = page.rect.width, page.rect.height
            words = [w[:5] for w in page.get_text("words")]
            if pno == 1:
                head = [w for w in words if w[3] <= HEADER_PT]
                title = clean(join_words(head), 140)
            body = [w for w in words if w[1] >= HEADER_PT]
            pages.append(clean(join_words(body), MAX_PAGE_TEXT))
            for f in info["fields"]:
                labels[f["id"]] = label_for(f, words, pw, ph)
        out[doc_id] = {"title": title, "pages": pages, "labels": labels}
        found = sum(1 for v in labels.values() if v)
        print(f"{doc_id:40s} fields={len(labels):3d} labelled={found:3d}")

    OUT.write_text(
        "// Generated by scripts/worksheets/context.py — do not edit by hand.\n"
        "// Printed text next to each worksheet field, used by the AI summary.\n"
        "// Server only: nothing in src/ imports this file.\n"
        "const context = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "export default context;\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
